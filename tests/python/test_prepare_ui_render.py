import importlib.util
from pathlib import Path
import sys
from types import SimpleNamespace

import pytest

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('prepare_ui_render', ROOT / 'tools/prepare_ui_render.py')
assert spec and spec.loader
prepare_ui = importlib.util.module_from_spec(spec)
spec.loader.exec_module(prepare_ui)


@pytest.fixture
def manager(monkeypatch):
    calls = []
    component = SimpleNamespace(component_hash='locked-hash', version='9.6.0')

    class Lock:
        def __init__(self, path):
            calls.append(('lock', path))

        def load(self):
            return SimpleNamespace(solved_components={'lvgl/lvgl': component})

    class Fetch:
        def __init__(self, requested, directory):
            assert requested is component
            self.directory = directory

        def download(self):
            calls.append(('fetch', self.directory))
            destination = self.directory / 'lvgl__lvgl'
            destination.mkdir(parents=True)
            (destination / 'source.c').write_text('locked')
            return destination

    def validate(path, digest):
        calls.append(('validate', path, digest))
        if (path / 'source.c').read_text() != 'locked' or {
                str(p.relative_to(path)) for p in path.rglob('*') if p.is_file()} != {'source.c'}:
            raise RuntimeError('component hash mismatch')

    for name, value in {
        'idf_component_tools.hash_tools.validate': SimpleNamespace(validate_hash_eq_hashdir=validate),
        'idf_component_tools.lock': SimpleNamespace(LockManager=Lock),
        'idf_component_tools.sources.fetcher': SimpleNamespace(ComponentFetcher=Fetch),
    }.items():
        monkeypatch.setitem(sys.modules, name, value)
    return calls, Fetch


def test_fetches_only_locked_lvgl_and_validates(tmp_path, manager):
    lock_before = (ROOT / 'dependencies.lock').read_bytes()
    calls, _ = manager
    prepare_ui.prepare(tmp_path)
    assert calls == [('lock', ROOT / 'dependencies.lock'), ('fetch', tmp_path),
                     ('validate', tmp_path / 'lvgl__lvgl', 'locked-hash')]
    assert [p.name for p in tmp_path.iterdir()] == ['lvgl__lvgl']
    assert (ROOT / 'dependencies.lock').read_bytes() == lock_before


def test_existing_modified_component_is_rejected_without_fetch_or_overwrite(tmp_path, manager):
    destination = tmp_path / 'lvgl__lvgl'
    destination.mkdir()
    source = destination / 'source.c'
    source.write_text('local work')
    calls, _ = manager
    with pytest.raises(RuntimeError, match='hash mismatch'):
        prepare_ui.prepare(tmp_path)
    assert not any(call[0] == 'fetch' for call in calls)
    assert source.read_text() == 'local work'


def test_existing_valid_component_is_not_downloaded_again(tmp_path, manager):
    prepare_ui.prepare(tmp_path)
    manager[0].clear()
    prepare_ui.prepare(tmp_path)
    assert [call[0] for call in manager[0]] == ['lock', 'validate']


def test_download_failure_never_reports_ready(tmp_path, manager, monkeypatch, capsys):
    monkeypatch.setattr(manager[1], 'download', lambda self: None)
    with pytest.raises(RuntimeError, match='not downloaded'):
        prepare_ui.prepare(tmp_path)
    assert 'ready' not in capsys.readouterr().out


def test_generated_bytecode_is_excluded_without_deleting_or_changing_vendor_files(tmp_path, manager):
    prepare_ui.prepare(tmp_path)
    cache = tmp_path / 'lvgl__lvgl/scripts/__pycache__/module.pyc'
    cache.parent.mkdir(parents=True)
    cache.write_bytes(b'generated bytecode')
    manager[0].clear()
    prepare_ui.prepare(tmp_path)
    assert cache.read_bytes() == b'generated bytecode'
    assert (tmp_path / 'lvgl__lvgl/source.c').read_text() == 'locked'
    assert not any(call[0] == 'fetch' for call in manager[0])


def test_extra_source_inside_cache_directory_is_still_rejected(tmp_path, manager):
    prepare_ui.prepare(tmp_path)
    cache = tmp_path / 'lvgl__lvgl/scripts/__pycache__'
    cache.mkdir(parents=True)
    (cache / 'module.pyc').write_bytes(b'generated')
    (cache / 'extra.c').write_text('unlocked source')
    with pytest.raises(RuntimeError, match='hash mismatch'):
        prepare_ui.prepare(tmp_path)
    assert (cache / 'extra.c').read_text() == 'unlocked source'
