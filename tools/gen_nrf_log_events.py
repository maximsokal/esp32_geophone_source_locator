#!/usr/bin/env python3
"""Generate the WebUI nRF log event-name table from the shared X-macro list."""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
EVENTS_DEF = ROOT / "nRF54L15" / "include" / "nrf_log_events.def"
OUTPUT = ROOT / "webui" / "src" / "features" / "nrflog" / "nrfLogEvents.gen.ts"
ROW = re.compile(r"X\(\s*(\d+)\s*,\s*([A-Z][A-Z0-9_]*)\s*,\s*([A-Z][A-Z0-9_]*)\s*,\s*(DEBUG|INFO|WARN|ERROR|FATAL)\s*\)")
SUBSYSTEMS = {"BOOT", "LOG", "TWIS", "TOPOLOGY", "SENSOR", "CALIBRATION", "CS", "WATCHDOG", "POWER"}


class EventDefinitionError(ValueError):
    pass


def parse_events(source: str) -> list[tuple[int, str, str, str]]:
    events: list[tuple[int, str, str, str]] = []
    ids: set[int] = set()
    names: set[str] = set()
    for line_number, raw_line in enumerate(source.splitlines(), start=1):
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        match = ROW.fullmatch(line)
        if match is None:
            raise EventDefinitionError(f"line {line_number}: invalid event row")
        event_id = int(match.group(1))
        name, subsystem, severity = match.group(2), match.group(3), match.group(4)
        if event_id < 1 or event_id > 0xFFFF:
            raise EventDefinitionError(f"line {line_number}: event id out of range")
        if event_id in ids:
            raise EventDefinitionError(f"line {line_number}: duplicate event id {event_id}")
        if name in names:
            raise EventDefinitionError(f"line {line_number}: duplicate event name {name}")
        if subsystem not in SUBSYSTEMS:
            raise EventDefinitionError(f"line {line_number}: unknown subsystem {subsystem}")
        ids.add(event_id)
        names.add(name)
        events.append((event_id, name, subsystem, severity))
    if not events:
        raise EventDefinitionError("event definition is empty")
    return events


def generate(events: list[tuple[int, str, str, str]]) -> str:
    lines = [
        "/* Generated by tools/gen_nrf_log_events.py; edit nrf_log_events.def. */",
        "export const NRF_LOG_EVENTS = {",
    ]
    for event_id, name, subsystem, severity in events:
        lines.append(
            f'  {event_id}: {{ name: "{name}", subsystem: "{subsystem}", defaultSeverity: "{severity}" }},'
        )
    lines.extend(("} as const;", ""))
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated TypeScript is stale")
    args = parser.parse_args(argv)
    try:
        events = parse_events(EVENTS_DEF.read_text(encoding="utf-8"))
    except (OSError, EventDefinitionError) as exc:
        print(f"nRF log event generation failed: {exc}", file=sys.stderr)
        return 1
    generated = generate(events)
    if args.check:
        try:
            current = OUTPUT.read_text(encoding="utf-8")
        except OSError:
            current = None
        if current != generated:
            print(f"generated file is stale: {OUTPUT.relative_to(ROOT).as_posix()}", file=sys.stderr)
            return 1
        print("generated nRF log event table is current")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
