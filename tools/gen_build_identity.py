#!/usr/bin/env python3
"""Writes main/app_build_identity.c content: which source tree the ESP32 firmware was built from (CS-IDENTITY-01).

Usage: gen_build_identity.py --repo ROOT --out FILE

The ESP-IDF "App version" and "Compile time" lines come from esp_app_desc.c, which is only rebuilt when CMake is
configured again: an incremental build of changed sources keeps the old commit and time (bench 2026-11-02: the log said
349151c4 / 14:41:04 while the binary already contained the audit changes made later). This identity is regenerated by
every build and depends only on the tree, so it changes exactly when the built sources change:

    <12 hex of HEAD>                        the tree equals that commit
    <12 hex of HEAD>+dirty.<8 hex>          tracked files differ; the 8 hex are a hash of `git diff HEAD`, so two different
                                            uncommitted states never share an identity
    unknown                                 git is missing or ROOT is not a repository

Untracked files are not part of it (the same rule as nRF54L15/cmake/write_build_info.cmake). The file is rewritten only
when its content changes, so an unchanged tree does not cause a rebuild.
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

COMMIT_CHARS = 12
DIFF_CHARS = 8


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess[bytes] | None:
    try:
        return subprocess.run(["git", *args], cwd=repo, capture_output=True, check=False, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return None


def identity(repo: Path) -> str:
    head = _git(repo, "rev-parse", "--verify", "HEAD")
    if head is None or head.returncode != 0:
        return "unknown"
    commit = head.stdout.decode("ascii", "replace").strip()[:COMMIT_CHARS]
    if len(commit) != COMMIT_CHARS:
        return "unknown"
    status = _git(repo, "diff-index", "--quiet", "--ignore-submodules=untracked", "HEAD", "--")
    if status is None or status.returncode not in (0, 1):
        return "unknown"
    if status.returncode == 0:
        return commit
    diff = _git(repo, "diff", "HEAD", "--binary", "--ignore-submodules=untracked")
    if diff is None or diff.returncode != 0:
        return f"{commit}+dirty.unknown"
    return f"{commit}+dirty.{hashlib.sha256(diff.stdout).hexdigest()[:DIFF_CHARS]}"


def render(value: str) -> str:
    # The value is built from hex digits, '+', '.' and 'unknown': nothing that needs C escaping, and this keeps it so.
    assert all(c.isalnum() or c in "+." for c in value), value
    return (
        "/* generated by tools/gen_build_identity.py: do not edit */\n"
        '#include "app_build_identity.h"\n\n'
        f'const char app_build_identity[] = "{value}";\n'
    )


def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="ascii") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="ascii", newline="\n")
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)
    value = identity(args.repo)
    changed = write_if_changed(args.out, render(value))
    print(f"build identity {value}{' (written)' if changed else ' (unchanged)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
